import assert from 'node:assert/strict';
import { readHistory, saveHistory } from './src/matchArchive.ts';
import { Chess } from 'chess.js';
let saved;
globalThis.localStorage = { getItem: () => saved ?? null, setItem: (_, value) => { saved = value; } };
const base = { id: 'first', startedAt: new Date().toISOString(), updatedAt: new Date().toISOString(), bossIndex: 0, opponent: 'Test opponent', elo: 100, color: 'b', pgn: '1. f3 e5 2. g4 Qh4#', result: 'win', reason: 'Checkmate' };
assert.deepEqual(readHistory(), []);
assert.equal(saveHistory([base, { ...base, id: 'second', pgn: '', result: 'loss', reason: 'Resignation' }]), true);
assert.equal(readHistory().length, 2);
const restored = new Chess(); restored.loadPgn(readHistory()[0].pgn);
assert.equal(restored.isCheckmate(), true);
assert.equal(restored.history().length, 4);
assert.equal(readHistory()[1].reason, 'Resignation');
saved = JSON.stringify([base, { ...base, id: 'broken', pgn: '1. invalid' }]);
assert.equal(readHistory().length, 1);
saved = 'broken json'; assert.deepEqual(readHistory(), []);
globalThis.localStorage.setItem = () => { throw new Error('quota'); };
assert.equal(saveHistory([base]), false);
console.log('PASS archive round trip, multiple games, full move restoration, empty resignation, corrupt entry isolation, storage failure');
