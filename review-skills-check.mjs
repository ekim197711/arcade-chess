import assert from 'node:assert/strict';
import { Chess } from 'chess.js';
import { evaluateReviewSkills } from './src/reviewSkills.ts';

const game = new Chess();
game.loadPgn('1. e4 e5 2. Nf3 Nc6 3. Bc4 Nf6');
const moves = game.history({ verbose: true });
const analysis = (loss, line = ['e4']) => ({ loss, playedLine: line, suggestedLine: line });
const scores = (data, color = 'w', history = moves) => Object.fromEntries(evaluateReviewSkills(history, data, color).map(s => [s.name, s]));
assert.equal(scores({}).Opening.elo, null);
assert.equal(scores({ 0: analysis(0), 2: analysis(0) }).Opening.elo, null);
const good = { 0: analysis(0), 2: analysis(0), 4: analysis(0) };
assert.equal(scores(good).Opening.elo, 2400);
assert.equal(scores(good, 'b').Opening.elo, null);
assert.equal(scores(good).Endgame.elo, null);
const poor = { 0: analysis(200), 2: analysis(200), 4: analysis(200) };
assert.ok(scores(poor).Opening.elo < scores(good).Opening.elo);
const tactical = Object.fromEntries([0, 2, 4].map(i => [i, { ...analysis(100), suggestedLine: ['Qxf7#'] }]));
assert.equal(scores(tactical).Tactics.moves, 3);
assert.ok(scores(tactical).Tactics.elo !== null);
const ending = new Chess('8/7k/8/8/8/8/P7/K7 w - - 0 20');
for (const san of ['a3', 'Kg6', 'a4', 'Kf6', 'a5']) ending.move(san);
const endScores = scores(good, 'w', ending.history({ verbose: true }));
assert.equal(endScores.Endgame.moves, 3);
assert.equal(endScores.Opening.moves, 0);
const quietMiddle = moves.map(m => ({ ...m, before: m.before.replace(/\d+$/, '11') }));
assert.equal(scores(good, 'w', quietMiddle).Strategy.moves, 3);
assert.equal(scores({ 0: analysis(NaN) }).Opening.moves, 0);
console.log('PASS skill estimates: minimum samples, player filtering, quality, missed tactics, phases, invalid loss');
